#!/usr/bin/env node
/* Bundle engine/knowledge/exemplars/*.html into engine/knowledge/exemplars.ts (string constants) so the
   premium prompt works in Node, Deno (edge function) and the browser bundle without file access. */
const fs = require('fs'); const path = require('path');
const dir = path.join(__dirname, '..', 'engine', 'knowledge', 'exemplars');
const META = {
  'gochang-05-numbers': { kinds: ['numbers', 'story', 'list'], title: '숫자 카드 2행(그룹 헤더+KPI 타일) + 오른쪽 추세 패널 + 결론 카드' },
  'ir-04-market-slider': { kinds: ['chart', 'demo'], title: '인터랙티브 데모: 정적 표 ↔ SVG 차트 토글 + 연도 슬라이더 자동 스윕 + 오른쪽 순환 카드' },
  'gochang-21-prompt-formula': { kinds: ['process', 'concept'], title: '4칸(+1) 공식 → 조립된 결과 컴포저(순차 등장)' },
  'gochang-10-three-companies': { kinds: ['compare', 'concept'], title: '3열 비교 카드(성격·강점·수치) + 하단 결론 밴드' },
};
const out = [];
out.push('/* AUTO-GENERATED by scripts/make-exemplars.cjs — do not edit. Trimmed slides from the reference decks (body HTML + per-slide CSS/JS). */');
out.push('export interface Exemplar { id: string; title: string; kinds: string[]; text: string }');
out.push('export const EXEMPLARS: Record<string, Exemplar> = {');
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.html')).sort()) {
  const id = f.replace(/\.html$/, ''); const m = META[id]; if (!m) continue;
  const text = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r/g, '');
  out.push(`  ${JSON.stringify(id)}: { id: ${JSON.stringify(id)}, title: ${JSON.stringify(m.title)}, kinds: ${JSON.stringify(m.kinds)}, text: ${JSON.stringify(text)} },`);
}
out.push('};');
out.push('');
out.push('/** Pick exemplars for a slide kind: the kind-specific one first, then a complementary one. */');
out.push('export function exemplarsFor(kind: string): Exemplar[] {');
out.push("  const order: Record<string, string[]> = { numbers: ['gochang-05-numbers', 'ir-04-market-slider'], chart: ['ir-04-market-slider', 'gochang-05-numbers'], demo: ['ir-04-market-slider', 'gochang-21-prompt-formula'], process: ['gochang-21-prompt-formula', 'gochang-05-numbers'], compare: ['gochang-10-three-companies', 'gochang-05-numbers'], concept: ['gochang-10-three-companies', 'gochang-21-prompt-formula'], story: ['gochang-05-numbers', 'gochang-10-three-companies'], list: ['gochang-10-three-companies', 'gochang-05-numbers'] };");
out.push("  const ids = order[kind] || order.story;");
out.push('  return ids.map(id => EXEMPLARS[id]).filter(Boolean);');
out.push('}');
fs.writeFileSync(path.join(dir, '..', 'exemplars.ts'), out.join('\n') + '\n');
console.log('exemplars.ts written:', Object.keys(META).length, 'exemplars');
