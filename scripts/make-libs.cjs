#!/usr/bin/env node
/* Bundle third-party runtime libraries into engine/assets/libs.ts as JSON-escaped strings (injected into slide/player HTML only when used).
   gsap 3.12.5 (GreenSock standard license, free), three.js r152 (MIT), modern-screenshot 4.7.0 (MIT), scenes.js (deck scene kit ported from the 고창 reference deck: terrain / network / cubes / fireflies). */
const fs = require('fs'); const path = require('path');
const dir = path.join(__dirname, '..', 'engine', 'assets', 'libs');
const files = { GSAP_JS: 'gsap.min.js', THREE_JS: 'three.min.js', SNAPSHOT_JS: 'modern-screenshot.js', SCENES_JS: 'scenes.js' };
let out = '/* AUTO-GENERATED by scripts/make-libs.cjs — third-party runtime libraries as strings. */\n';
for (const [name, f] of Object.entries(files)) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8').replace(/<\/script>/gi, '<\\/script>');
  out += `export const ${name}: string = ${JSON.stringify(src)};\n`;
}
fs.writeFileSync(path.join(dir, '..', 'libs.ts'), out);
console.log('libs.ts', (out.length / 1024).toFixed(0) + 'KB');
